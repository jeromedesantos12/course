DROP DATABASE IF EXISTS sekolah_2018;

CREATE DATABASE sekolah_2018;

USE sekolah_2018;

-- membuat tabel-tabel

CREATE TABLE siswa (
       nis char(10) PRIMARY KEY,
       nama varchar(100) NOT NULL,
       nisn varchar(20) UNIQUE,
       nama_orangtua varchar(100)
);

CREATE TABLE sekolah (
       id char(6) PRIMARY KEY,
       nama varchar(100) NOT NULL,
       alamat varchar(200)
);

CREATE TABLE guru (
       nip varchar(10) PRIMARY KEY,
       nama varchar(100) NOT NULL
);

CREATE TABLE kelas (
       kode varchar(10) PRIMARY KEY,
       nama varchar(20) NOT NULL
);

CREATE TABLE kelompok_pelajaran (
       id int UNSIGNED AUTO_INCREMENT PRIMARY KEY,
       nama varchar(20) NOT NULL
);

CREATE TABLE mata_pelajaran (
       kode varchar(10) PRIMARY KEY,
       nama varchar(100) NOT NULL,
       tipe enum('kulikuler', 'ekskul') DEFAULT 'kulikuler',
       kelompok_id int UNSIGNED,
       FOREIGN KEY (kelompok_id) REFERENCES kelompok_pelajaran(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tahun_pelajaran (
       kode varchar(10) PRIMARY KEY,
       tahun year NOT NULL,
       aktif boolean DEFAULT false,
       semester enum('ganjil', 'genap') NOT NULL
);

CREATE TABLE kelas_siswa (
       id int UNSIGNED AUTO_INCREMENT PRIMARY KEY,
       siswa_nis char(10) NOT NULL,
       tapel_kode varchar(10) NOT NULL,
       wali_kelas varchar(10) NOT NULL,
       kelas_kode varchar(10) NOT NULL,
       FOREIGN KEY (siswa_nis) REFERENCES siswa(nis) ON UPDATE CASCADE ON DELETE RESTRICT,
       FOREIGN KEY (tapel_kode) REFERENCES tahun_pelajaran(kode) ON UPDATE CASCADE ON DELETE RESTRICT,
       FOREIGN KEY (wali_kelas) REFERENCES guru(nip) ON UPDATE CASCADE ON DELETE RESTRICT,
       FOREIGN KEY (kelas_kode) REFERENCES kelas(kode) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE rapor (
       id int UNSIGNED AUTO_INCREMENT PRIMARY KEY,
       sekolah_id char(6) NOT NULL,
       siswa_nis char(10) NOT NULL,
       tapel_kode varchar(10) NOT NULL,
       sikap_antar_mapel enum('SB', 'B', 'C', 'K') NOT NULL,
       sakit smallint(2) UNSIGNED,
       izin smallint(2) UNSIGNED,
       tanpa_keterangan smallint(2) UNSIGNED,
       tanggal date NOT NULL,
       FOREIGN KEY (sekolah_id) REFERENCES sekolah(id) ON UPDATE CASCADE ON DELETE RESTRICT,
       FOREIGN KEY (siswa_nis) REFERENCES siswa(nis) ON UPDATE CASCADE ON DELETE RESTRICT,
       FOREIGN KEY (tapel_kode) REFERENCES tahun_pelajaran(kode) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE capaian (
       id int UNSIGNED AUTO_INCREMENT PRIMARY KEY,
       rapor_id int UNSIGNED NOT NULL,
       mapel_kode varchar(10) NOT NULL,
       pengetahuan_angka tinyint(3) UNSIGNED NOT NULL,
       keterampilan_angka tinyint(3) UNSIGNED NOT NULL,
       pengetahuan_predikat char(1) NOT NULl,
       keterampilan_predikat char(1) NOT NULl,
       sikap varchar(100) NOT NULL,
       FOREIGN KEY (rapor_id) REFERENCES rapor(id) ON UPDATE CASCADE ON DELETE RESTRICT,
       FOREIGN KEY (mapel_kode) REFERENCES mata_pelajaran(kode) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE nilai_ekskul (
       id int UNSIGNED AUTO_INCREMENT PRIMARY KEY,
       rapor_id int UNSIGNED NOT NULL,
       ekskul_kode varchar(10) NOT NULL,
       keikutsertaan varchar(100) NOT NULL,
       FOREIGN KEY (rapor_id) REFERENCES rapor(id) ON UPDATE CASCADE ON DELETE RESTRICT,
       FOREIGN KEY (ekskul_kode) REFERENCES mata_pelajaran(kode) ON UPDATE CASCADE ON DELETE RESTRICT
);


